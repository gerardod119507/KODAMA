-- =====================================================================
-- KODAMA · Migración 002: el orden de las filas
-- =====================================================================
-- Ya aplicada (16 oct 2026).
--
-- El Sheet tenía un orden natural: el de las filas (los cursos de 1ro a
-- 6to, los alumnos en el orden en que se cargaron). Postgres no garantiza
-- ningún orden sin ORDER BY, así que cada tabla lleva un número que crece
-- solo con cada fila nueva, y la app lee siempre ordenando por él. Las
-- filas que ya estaban se numeraron en el orden en que se importaron, que
-- es el mismo del Sheet.
-- =====================================================================

alter table public.areas add column orden bigint generated by default as identity;
alter table public.cursos add column orden bigint generated by default as identity;
alter table public.colegios add column orden bigint generated by default as identity;
alter table public.alumnos add column orden bigint generated by default as identity;
alter table public.horario add column orden bigint generated by default as identity;
alter table public.bloques add column orden bigint generated by default as identity;
alter table public.pagos add column orden bigint generated by default as identity;
alter table public.plantillas add column orden bigint generated by default as identity;
